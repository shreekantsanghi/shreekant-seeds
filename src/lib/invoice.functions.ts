import { createServerFn } from "@tanstack/react-start";
import { z } from "zod";
import type { SupabaseClient } from "@supabase/supabase-js";
import { requireSupabaseAuth } from "@/integrations/supabase/auth-middleware";
import { assertAdmin } from "@/lib/admin-catalog.functions";
import { toItem } from "@/lib/customer-orders.functions";
import type { Database } from "@/integrations/supabase/types";
import type { OrderAddressSnapshot } from "@/lib/orders-shared";
import type { InvoiceData } from "@/lib/invoice-shared";

/**
 * Phase 6 — invoice reads.
 *
 * Both entry points run as the signed-in user, so RLS remains the authority:
 * a customer can only reach their own order, and the merchant path additionally
 * requires an active admin profile. The invoice number is generated by the
 * server-side routine `issue_order_invoice`, never in the browser, and only for
 * orders whose payment is already confirmed.
 */

type Client = SupabaseClient<Database>;

const ORDER_COLUMNS =
  "id, order_number, status, payment_status, created_at, customer_name, customer_phone, delivery_address, delivery_distance_km, invoice_number, invoice_issued_at, subtotal, discount_amount, delivery_charge, taxable_value, cgst_amount, sgst_amount, igst_amount, tax_amount, total_amount";

const ITEM_COLUMNS =
  "id, product_name, product_name_hi, product_type, pack_size, unit, sku, hsn_code, quantity, unit_price, tax_rate, tax_amount, total_price";

const num = (value: number | string | null | undefined): number => (value === null || value === undefined ? 0 : Number(value));

async function buildInvoice(supabase: Client, orderId: string, ownerId: string | null): Promise<InvoiceData | null> {
  let query = supabase.from("orders").select(ORDER_COLUMNS).eq("id", orderId);
  if (ownerId) query = query.eq("user_id", ownerId);
  const { data: row, error } = await query.maybeSingle();
  if (error) throw error;
  if (!row) return null;

  let invoiceNumber = row.invoice_number;
  let invoiceIssuedAt = row.invoice_issued_at;

  // Issue (or reuse) the number server-side, paid orders only.
  if (!invoiceNumber && row.payment_status === "paid") {
    const { data: issued, error: issueError } = await supabase.rpc("issue_order_invoice", { p_order_id: orderId });
    if (issueError) throw issueError;
    if (issued) {
      invoiceNumber = issued as string;
      invoiceIssuedAt = new Date().toISOString();
    }
  }

  const { data: itemRows, error: itemError } = await supabase
    .from("order_items")
    .select(ITEM_COLUMNS)
    .eq("order_id", orderId)
    .order("created_at", { ascending: true });
  if (itemError) throw itemError;

  return {
    invoiceNumber,
    invoiceIssuedAt,
    orderId: row.id,
    orderNumber: row.order_number,
    orderDate: row.created_at,
    status: row.status,
    paymentStatus: row.payment_status,
    isPaid: row.payment_status === "paid",
    customerName: row.customer_name,
    customerPhone: row.customer_phone,
    deliveryAddress: (row.delivery_address as OrderAddressSnapshot | null) ?? null,
    deliveryDistanceKm: row.delivery_distance_km === null ? null : Number(row.delivery_distance_km),
    subtotal: num(row.subtotal),
    discountAmount: num(row.discount_amount),
    deliveryCharge: num(row.delivery_charge),
    taxableValue: num(row.taxable_value),
    cgstAmount: num(row.cgst_amount),
    sgstAmount: num(row.sgst_amount),
    igstAmount: num(row.igst_amount),
    taxAmount: num(row.tax_amount),
    totalAmount: num(row.total_amount),
    items: ((itemRows ?? []) as Parameters<typeof toItem>[0][]).map(toItem),
  };
}

/** Customer invoice. RLS plus the explicit user_id filter block another customer's id. */
export const getMyInvoice = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .validator((input: unknown) => z.object({ orderId: z.string().uuid() }).parse(input))
  .handler(async ({ data, context }): Promise<InvoiceData | null> =>
    buildInvoice(context.supabase, data.orderId, context.userId),
  );

/** Merchant invoice. Requires an active admin profile, then reads under is_admin() policies. */
export const getAdminInvoice = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .validator((input: unknown) => z.object({ orderId: z.string().uuid() }).parse(input))
  .handler(async ({ data, context }): Promise<InvoiceData | null> => {
    await assertAdmin(context);
    return buildInvoice(context.supabase, data.orderId, null);
  });
